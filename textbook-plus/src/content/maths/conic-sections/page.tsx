      <KeyPoint title="Properties of Hyperbola">
        <ul>
          <li><strong>Transverse axis:</strong> the axis passing through the foci. Length = 2a.</li>
          <li><strong>Conjugate axis:</strong> perpendicular to transverse axis through the centre. Length = 2b.</li>
          <li><strong>Vertices:</strong> (±a, 0) — endpoints of the transverse axis.</li>
          <li><strong>Foci:</strong> (±c, 0) where c² = a² + b².</li>
          <li><strong>Eccentricity:</strong> e = c/a &gt; 1 (always greater than 1 for hyperbola).</li>
          <li><strong>Asymptotes:</strong> y = ±(b/a)x — the hyperbola approaches these lines at infinity.</li>
        </ul>
      </KeyPoint>

