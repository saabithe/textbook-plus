      <SpeedTricks>
        <Callout type="tip" title="Which is a, which is b?">
          Always: a &gt; b. If the larger denominator is under x², major axis is horizontal. If under y², vertical. Don&apos;t assume a is always under x².
        </Callout>
        <Callout type="tip" title="a² = b² + c² (not c² = a² + b²)">
          Common exam trap: for ellipse, c² = a² − b² (so a² = b² + c²). For hyperbola, c² = a² + b². The roles of a and c are different.
        </Callout>
      </SpeedTricks>

