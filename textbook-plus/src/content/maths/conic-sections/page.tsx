      <SpeedTricks>
        <Callout type="tip" title="Ellipse: a² = b² + c². Hyperbola: c² = a² + b²">
          In an ellipse, the focus is <em>inside</em> — so c &lt; a. In a hyperbola, the focus is <em>outside</em> — so c &gt; a. That&apos;s why the ± sign flips between the two formulas.
        </Callout>
        <Callout type="tip" title="Identifying the curve from its equation">
          x²/A + y²/B = 1 → ellipse (A, B positive). x²/A − y²/B = 1 → hyperbola. y² = 4ax → parabola. x² + y² = r² → circle.
        </Callout>
      </SpeedTricks>

