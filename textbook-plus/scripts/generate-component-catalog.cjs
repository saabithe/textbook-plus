/**
 * Generates the component-library catalog + module registry from the filesystem.
 *
 *   node scripts/generate-component-catalog.cjs
 *
 * Outputs:
 *   src/app/dev/components/catalog.generated.ts
 *   src/app/dev/components/catalog.generated.json   (used by verify:catalog)
 *   src/app/dev/components/registry.generated.tsx
 *
 * The catalog is the completeness contract: every .tsx file and every export
 * must appear here, or verify:catalog fails.
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..", "src", "components");
const OUT = path.join(__dirname, "..", "src", "app", "dev", "components");

const SHELL = new Set([
  "chapter/ChapterLayout.tsx",
  "layout/Navbar.tsx",
  "layout/ThemeProvider.tsx",
  "layout/ServiceWorkerRegistration.tsx",
  "search/SearchModal.tsx",
  "annotate/AnnotationLayer.tsx",
  "annotate/SelectionToolbar.tsx",
]);

function walk(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (entry.name.endsWith(".tsx")) out.push(full);
  }
  return out;
}

function rel(full) {
  return path.relative(ROOT, full).split(path.sep).join("/");
}

function categoryOf(relPath) {
  if (relPath.startsWith("ui/")) return "ui";
  if (relPath.startsWith("content/chemistry/")) return "chemistry";
  if (relPath.startsWith("content/physics/")) return "physics";
  if (relPath.startsWith("content/biology/")) return "biology";
  if (relPath.startsWith("content/concept/")) return "concept";
  if (relPath.startsWith("content/data/")) return "data";
  if (relPath.startsWith("content/process/")) return "process";
  if (relPath.startsWith("content/study/")) return "study";
  if (relPath.startsWith("content/")) return "content";
  if (relPath.startsWith("chapter/")) return "chapter";
  if (relPath.startsWith("practice/")) return "practice";
  if (relPath.startsWith("flashcard/")) return "flashcard";
  if (relPath.startsWith("grammar/")) return "grammar";
  return "shell";
}

function exportsOf(source) {
  const names = new Set();
  for (const m of source.matchAll(/^export (?:async )?function (\w+)/gm)) names.add(m[1]);
  for (const m of source.matchAll(/^export (?:const|class) (\w+)/gm)) names.add(m[1]);
  for (const m of source.matchAll(/^export default (?:class|function) (\w+)/gm)) names.add(m[1]);
  for (const m of source.matchAll(/^export\s*\{([^}]+)\}/gm)) {
    for (let part of m[1].split(",")) {
      part = part.trim();
      if (!part || part.startsWith("type ")) continue;
      const name = part.split(/\s+as\s+/).pop().trim();
      if (/^\w+$/.test(name)) names.add(name);
    }
  }
  return [...names];
}

function isRenderable(name) {
  if (/^use[A-Z]/.test(name)) return false;
  if (/Variants$/.test(name)) return false;
  if (name === "renderElement") return false;
  if (name === "navigationMenuTriggerStyle") return false;
  if (name === "CarouselApi") return false;
  return true;
}

function propsOf(source) {
  const m = source.match(/(?:interface|type) \w+Props\s*(?:=\s*)?\{([\s\S]*?)\n\}/);
  if (!m) return null;
  const text = m[1]
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .replace(/\/\/[^\n]*/g, " ")
    .replace(/\s+/g, " ")
    .trim();
  return text ? text.slice(0, 320) : null;
}

const files = walk(ROOT).sort();
const catalog = [];
const registry = [];

for (const full of files) {
  const relPath = rel(full);
  const source = fs.readFileSync(full, "utf8");
  const exports = exportsOf(source);
  const shell = SHELL.has(relPath);
  const renderables = exports.filter(isRenderable);

  for (const name of exports) {
    catalog.push({
      id: `${relPath}#${name}`,
      name,
      path: relPath,
      category: categoryOf(relPath),
      props: propsOf(source),
      shell,
      renderable: !shell && isRenderable(name),
    });
  }

  if (!shell && renderables.length > 0) {
    const alias = `m${registry.length}`;
    registry.push({ alias, relPath });
  }
}

const categoryOrder = [
  "ui",
  "content",
  "data",
  "process",
  "study",
  "concept",
  "chapter",
  "chemistry",
  "physics",
  "biology",
  "practice",
  "flashcard",
  "grammar",
  "shell",
];
catalog.sort((a, b) => {
  const ca = categoryOrder.indexOf(a.category);
  const cb = categoryOrder.indexOf(b.category);
  if (ca !== cb) return ca - cb;
  if (a.path !== b.path) return a.path.localeCompare(b.path);
  return a.name.localeCompare(b.name);
});

const ts = `/* AUTO-GENERATED by scripts/generate-component-catalog.cjs — do not edit by hand. */
export type ComponentCategory =
${categoryOrder.map((c) => `  | "${c}"`).join("\n")};

export interface CatalogEntry {
  id: string;
  name: string;
  path: string;
  category: ComponentCategory;
  props: string | null;
  shell: boolean;
  renderable: boolean;
}

export const CATEGORY_ORDER: ComponentCategory[] = ${JSON.stringify(categoryOrder)};

export const CATEGORY_LABEL: Record<ComponentCategory, string> = {
${categoryOrder.map((c) => `  ${c}: ${JSON.stringify(c[0].toUpperCase() + c.slice(1))},`).join("\n")}
};

export const CATALOG: CatalogEntry[] = ${JSON.stringify(catalog, null, 2)};
`;

fs.writeFileSync(path.join(OUT, "catalog.generated.ts"), ts);
fs.writeFileSync(path.join(OUT, "catalog.generated.json"), JSON.stringify(catalog, null, 2));

const imports = registry
  .map((r) => `import * as ${r.alias} from "@/components/${r.relPath.replace(/\.tsx$/, "")}";`)
  .join("\n");
const entries = registry
  .map((r) => `  ${JSON.stringify(r.relPath)}: ${r.alias} as unknown as Record<string, unknown>,`)
  .join("\n");

fs.writeFileSync(
  path.join(OUT, "registry.generated.tsx"),
  `/* AUTO-GENERATED by scripts/generate-component-catalog.cjs — do not edit by hand. */
${imports}

export const MODULES: Record<string, Record<string, unknown>> = {
${entries}
};
`
);

const byCategory = {};
for (const e of catalog) byCategory[e.category] = (byCategory[e.category] || 0) + 1;
console.log(`components: ${files.length}`);
console.log(`exports:    ${catalog.length}`);
console.log(`registry:   ${registry.length} modules`);
console.log(
  Object.entries(byCategory)
    .map(([k, v]) => `${k}=${v}`)
    .join("  ")
);
