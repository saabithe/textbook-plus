/**
 * Scans src/content/{subject}/{chapter}/chapter.json
 * and generates src/lib/blocknote/content-map.ts
 * with explicit imports so webpack can resolve them.
 *
 * Run: node scripts/generate-content-map.js
 * Runs automatically before build.
 */

const fs = require("fs");
const path = require("path");

const CONTENT_DIR = path.resolve(__dirname, "../src/content");
const OUTPUT_FILE = path.resolve(__dirname, "../src/lib/blocknote/content-map.ts");

function scanContent() {
  const entries = [];

  if (!fs.existsSync(CONTENT_DIR)) return entries;

  const subjects = fs.readdirSync(CONTENT_DIR).filter((s) => {
    return fs.statSync(path.join(CONTENT_DIR, s)).isDirectory();
  });

  for (const subject of subjects) {
    const subjectDir = path.join(CONTENT_DIR, subject);
    const chapters = fs.readdirSync(subjectDir).filter((c) => {
      return fs.statSync(path.join(subjectDir, c)).isDirectory();
    });

    for (const chapter of chapters) {
      const jsonPath = path.join(subjectDir, chapter, "chapter.json");
      if (fs.existsSync(jsonPath)) {
        entries.push({ subject, chapter });
      }
    }
  }

  return entries;
}

function generate(entries) {
  const imports = entries
    .map(
      (e, i) =>
        `import chapter_${i} from "@/content/${e.subject}/${e.chapter}/chapter.json";`
    )
    .join("\n");

  const mapEntries = entries
    .map(
      (e, i) =>
        `  "${e.chapter}": { subject: "${e.subject}", loader: () => Promise.resolve({ default: chapter_${i} as Block[] }) },`
    )
    .join("\n");

  const sectionsEntries = entries
    .map(
      (e) =>
        `  // ${e.subject}/${e.chapter} — add sections here or keep in content-loader.ts`
    )
    .join("\n");

  const content = `// AUTO-GENERATED by scripts/generate-content-map.js — do not edit manually
import type { Block } from "@blocknote/core";

${imports}

export const AUTO_BLOCKS_MAP: Record<string, { subject: string; loader: () => Promise<{ default: Block[] }> }> = {
${mapEntries}
};

// Sections are still manually maintained in content-loader.ts
// (they come from chapter metadata, not JSON files)
`;

  return content;
}

// Main
const entries = scanContent();
const output = generate(entries);

fs.mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true });
fs.writeFileSync(OUTPUT_FILE, output, "utf-8");

console.log(`Generated content-map.ts with ${entries.length} chapter(s):`);
for (const e of entries) {
  console.log(`  - ${e.subject}/${e.chapter}`);
}
